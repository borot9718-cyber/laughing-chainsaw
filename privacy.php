<h2>12. Suppression du compte</h2>
<p>KOVA permet désormais de demander la suppression du compte depuis les paramètres. Une confirmation par mot de passe est demandée avant l'exécution. Les données pouvant être supprimées sont supprimées, tandis que certaines traces nécessaires à la sécurité ou à des obligations applicables peuvent être minimisées ou anonymisées.</p>
<p>Lorsqu'un compte est supprimé, les sessions sont invalidées, les autorisations OAuth sont retirées, les données sociales directement rattachées au compte sont traitées selon leur nature et les coordonnées de livraison des commandes conservées pour traçabilité sont supprimées.</p>

