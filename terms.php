<h1>Conditions d’utilisation</h1>
<p><strong>Version 1.0 — dernière mise à jour : 19/09/2026</strong></p>
<h2>1. Utilisation du service</h2>
<p>KOVA est un espace social permettant de publier du contenu, communiquer avec d’autres membres, participer à des groupes et communautés et utiliser les fonctions de boutique proposées par la plateforme.</p>
<h2>2. Compte</h2>
<p>Vous devez fournir des informations exactes lors de l’inscription, protéger vos identifiants et ne pas utiliser le compte d’une autre personne. KOVA est accessible à partir de 16 ans.</p>
<h2>3. Contenus</h2>
<p>Vous restez responsable des contenus que vous publiez. Vous ne devez pas publier de contenu illicite, frauduleux, malveillant, portant atteinte aux droits d’autrui ou destiné à compromettre le fonctionnement du service.</p>
<h2>4. Sécurité et modération</h2>
<p>KOVA peut limiter, masquer ou supprimer un contenu et suspendre un compte lorsque cela est nécessaire pour la sécurité du service, le respect des règles de la plateforme ou des obligations applicables. Les utilisateurs peuvent utiliser les fonctions de signalement et d’assistance.</p>
<h2>5. Boutique</h2>
<p>Les commandes de la boutique sont actuellement réglées hors ligne. KOVA ne traite pas de paiement bancaire ou mobile en ligne dans la version actuelle. L’acheteur et le vendeur conviennent des modalités de paiement et de livraison nécessaires à la commande.</p>
<h2>6. Applications connectées</h2>
<p>La fonction « Continuer avec KOVA » permet à des applications enregistrées d’obtenir uniquement les informations correspondant aux autorisations accordées. Les autorisations peuvent être révoquées depuis les paramètres.</p>
<h2>7. Données personnelles</h2>
<p>Le traitement des données personnelles est décrit dans la <a href="/confidentialite">politique de confidentialité</a>. Les outils permettant l’export, la rectification, les demandes relatives aux droits et la suppression du compte sont disponibles depuis les paramètres.</p>
<h2>8. Disponibilité</h2>
<p>KOVA peut être temporairement indisponible pour maintenance, sécurité, mise à jour ou raison technique. Des mesures peuvent être prises pour protéger les utilisateurs et les données.</p>
